const getAssistantResponse = (query: string, products: any[]) => {
  const q = normalize(query);
  if (!q) return FALLBACK_ANSWER;

  // 1) Ստուգել հարց ու պատասխանների բազան
  let best: FaqItem | null = null;
  let bestScore = 0;
  for (const item of FAQ_DATA) {
    let score = 0;
    for (const key of item.keywords) {
      const k = normalize(key);
      if (k && q.includes(k)) score += k.length;
    }
    if (score > bestScore) {
      bestScore = score;
      best = item;
    }
  }

  // 2) Ստուգել ապրանքի անվանում կամ կոդ (եթե ապրանք է հիշատակված՝ այն ավելի կոնկրետ պատասխան է)
  const foundProducts = (products || [])
    .filter(p => !p.is_blocked)
    .filter(p => {
      const code = normalize(String(p.code || ''));
      const name = normalize(String(p.name || ''));
      return (code.length >= 2 && q.split(' ').includes(code)) || (name.length >= 3 && q.includes(name));
    })
    .slice(0, 3);

  if (foundProducts.length > 0) {
    let resp = "🔍 **Գտնված ապրանքներ**\n\n";
    foundProducts.forEach(p => {
      resp += `🔹 **${p.name}**\n💰 Գին՝ **${Number(p.price).toLocaleString()} ֏**\n🔢 Կոդ՝ **${p.code}**\n${p.category === 'sneakers' ? '👟 Սպորտային կոշիկ' : '🩴 Հողաթափ'}\n`;
      if (p.min_quantity && p.min_quantity > 1) resp += `📊 Նվազագույն քանակ՝ **${p.min_quantity}**\n`;
      resp += "\n";
    });
    resp += "💡 Ապրանքը զամբյուղ ավելացնելու համար մտեք համապատասխան բաժին և սեղմեք **«Ուղղարկել զամբյուղ»**։";
    return resp;
  }

  if (best) return best.answer;
  return FALLBACK_ANSWER;
};

